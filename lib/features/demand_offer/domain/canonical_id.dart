// КАНОН ФОЙДАЛАНУВЧИ ID — иловадаги жуфти.
//
// Сервердаги манба: `functions_demand/core/ids.js` (`toCanonicalId`).
//
// НЕГА КЕРАК: бу лойиҳада фойдаланувчи ID = телефон рақами, ва
// production'да 9 хонали (`901234567`) ҳамда 12 хонали
// (`998901234567`) ИККИ шакл ёнма-ён яшайди.
//
// Ядро базага ФАҚАТ 12 хонали шаклни ёзади. Шунинг учун илова ҳам
// сўровларда айни шу шаклни ишлатиши керак:
//   .where('providerId', isEqualTo: canonicalUserId(phone))
// Акс ҳолда 9 хонали ID билан сўров берилса, рўйхат БЎШ келади ва
// бунинг сабабини топиш қийин (хато чиқмайди, шунчаки ҳеч нарса йўқ).

/// `+998 90 123-45-67`, `901234567`, `998901234567` → `998901234567`.
///
/// Нотўғри узунликда БЎШ САТР қайтаради — жимгина «тузатилмайди»,
/// чақирувчи муаммони кўриши керак.
String canonicalUserId(String? raw) {
  final d = (raw ?? '').replaceAll(RegExp(r'\D'), '');
  if (d.length == 9) return '998$d';
  if (d.length == 12 && d.startsWith('998')) return d;
  return '';
}

/// Канон шаклдами.
bool isCanonicalUserId(String? v) =>
    RegExp(r'^998\d{9}$').hasMatch(v ?? '');

/// Иккита ID бир одамми (9/12 аралашганда ҳам).
///
/// Бўш қийматлар ТЕНГ ДЕБ ҲИСОБЛАНМАЙДИ — акс ҳолда
/// аутентификациясиз фойдаланувчи бошқанинг маълумотини кўрарди.
bool isSameUser(String? a, String? b) {
  final ca = canonicalUserId(a);
  final cb = canonicalUserId(b);
  return ca.isNotEmpty && ca == cb;
}
