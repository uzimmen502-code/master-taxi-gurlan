async function main() {
  const col = db.collection('home_ticker_ads');
  const existingSnap = await col.where('module', '==', 'home_search').get();
  const existingTexts = new Set(
    existingSnap.docs.map((d) => (d.data().text || '').trim()),
  );

  let added = 0;
  let skipped = 0;
  const batch = db.batch();

  TEXTS.forEach((text) => {
    const trimmed = text.trim();
    if (existingTexts.has(trimmed)) {
      skipped++;
      return;
    }
    const ref = col.doc();
    batch.set(ref, {
      text: trimmed,
      audience: 'all',
      module: 'home_search',
      active: true,
      priority: 0,
      durationSec: 4,
      scrollSpeed: 45,
      animationStyle: 'auto',
      fontSize: 13,
      createdAt: admin.firestore.FieldValue.serverTimestamp(),
      updatedAt: admin.firestore.FieldValue.serverTimestamp(),
    });
    added++;
  });

  if (added === 0) {
    console.log('Барча матнлар аллақачон мавжуд — қўшиладиган нарса йўқ.');
    return;
  }

  await batch.commit();
  console.log(`Қўшилди: ${added} та матн. Ўтказиб юборилди (дублика): ${skipped} та.`);
}

main()
  .then(() => process.exit(0))
  .catch((e) => {
    console.error('Хатолик:', e);
    process.exit(1);
  });
