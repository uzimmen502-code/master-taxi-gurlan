import 'package:uuid/uuid.dart';

/// Яратиш формаси учун `requestId` (C-2): 32 та hex белги (UUID v4, чизиқчасиз) —
/// серверлардаги `[A-Za-z0-9_-]{8,64}` қолипига мос. Форма очилганда БИР марта
/// ясалади ва шу форманинг ҳар уринишида юборилади: таймаутдан кейин қайта босиш
/// иккинчи ёзув ясамайди (сервер биринчи натижани қайтаради).
String newRequestId() => const Uuid().v4().replaceAll('-', '');

/// Пул ёки ўрин сарфлайдиган чақирувлар (харид, эълон яратиш) учун
/// ИДЕМПОТЕНТЛИК калитлари.
///
/// Қоида: ҳар «ният» (масалан «5 объектли пакет олиш») учун калит БИР МАРТА
/// ясалади ва шу ният тугагунча ўзгармайди. Аввал калит ҳар чақирувда янги
/// UUID бўларди — жавоб йўқолганда (таймаут) пул аллақачон ечилган бўлса ҳам
/// «Қайта уриниш» иккинчи калит билан иккинчи марта ечарди. Сервер айнан
/// бир хил калит келса натижани қайтаради, пулни қайта емайди.
///
/// [scope] — ният: масалан `pkg:5`, `pro:pro_25`. Бошқа ўлчам/режа — бошқа
/// калит (сервер ҳам калит билан бирга сўровни солиштиради).
class IdempotencyKeys {
  IdempotencyKeys({String Function()? generator}) : _gen = generator ?? (() => const Uuid().v4());

  final String Function() _gen;
  final Map<String, String> _keys = {};

  /// Шу ният учун калит (биринчи марта ясалади, кейин ўша қайтади).
  String keyFor(String scope) => _keys.putIfAbsent(scope, _gen);

  /// Ният ТУГАДИ (муваффақият ёки аниқ рад) — кейинги уриниш янги калит олади.
  void settled(String scope) => _keys.remove(scope);

  /// Ҳамма ниятни тозалайди.
  void clear() => _keys.clear();
}
