  /// Рухсат/лицензия эслатмаси бор турлар (эга рўйхатидаги изоҳ) — матн калити. Эслатма нашрни ТЎСМАЙДИ
  /// (эга 2026-11-03: лицензияли турлар — тиббиёт, молия, юридик/касбий, хавфсизлик, оила/болалар — текширувсиз
  /// дарҳол чиқади, фақат эслатма билан).
  static String? noteKey(BusinessCategory c) => switch (c) {
        BusinessCategory.health => 'business_cat_note_health',
        BusinessCategory.finance => 'business_cat_note_finance',
        BusinessCategory.professional => 'business_cat_note_professional',
        BusinessCategory.security => 'business_cat_note_security',
        BusinessCategory.family => 'business_cat_note_family',
        _ => null,
      };

  static String _name((String, String) e, String lang) => switch (lang) {
        'ru' => e.$2,
        'uz_Latn' => UzScript.toLatin(e.$1),
        _ => e.$1,
      };

  /// Солиштириш учун: кичик ҳарф, лотин ёзуви, апостроф турлари битта, ортиқча бўшлиқсиз.
  static String norm(String s) => UzScript.toLatin(s.trim().toLowerCase())
      .toLowerCase()
      .replaceAll(RegExp('[ʻʼʽˈ`´‘’′]'), "'")
      .replaceAll(RegExp(r'\s+'), ' ');

  /// [c] турининг аниқроқ турлари [lang] тилида (эга рўйхати тартибида).
  static List<String> of(BusinessCategory c, String lang) => [for (final e in data[c] ?? const []) _name(e, lang)];

  /// Сақланган матн тайёр турга мос келса (исталган тилда/ёзувда) — унинг [lang] даги номи; бўлмаса — ўзи.
  /// [category] берилса, аввал шу тур ичидан қидирилади (бир хил ном бир неча турда бўлиши мумкин).
  static String display(String stored, String lang, {BusinessCategory? category}) {
    final n = norm(stored);
    if (n.isEmpty) return stored;
    final order = [if (category != null) category, ...BusinessCategory.values.where((c) => c != category)];
    for (final c in order) {
      for (final e in data[c] ?? const <(String, String)>[]) {
        if (norm(e.$1) == n || norm(e.$2) == n) return _name(e, lang);
      }
    }
    return stored;
  }

  /// [stored] бошқа турнинг тайёр номи бўлиб, [c] да йўқ бўлса — `false` (тур алмашганда майдон тозаланади).
  /// Бўш ёки эганинг ўз матни — `true` (тегилмайди).
  static bool fits(String stored, BusinessCategory c) {
    final n = norm(stored);
    if (n.isEmpty) return true;
    bool inCat(BusinessCategory x) =>
        (data[x] ?? const <(String, String)>[]).any((e) => norm(e.$1) == n || norm(e.$2) == n);
    if (inCat(c)) return true;
    return !BusinessCategory.values.any(inCat);
  }

  /// «Аниқроқ тури» таклифлари: [category] берилса — фақат шу тур ичидан, бўлмаса — 30 турнинг ҳаммасидан
  /// (танланса тур ҳам белгиланади). Бўш сўров — турнинг бутун рўйхати (тур йўқ бўлса — бўш).
  static List<BusinessTypeOption> subtypeOptions(String query, String lang, {BusinessCategory? category}) {
    final q = norm(query);
    final cats = category == null ? BusinessCategory.values : [category];
    if (q.isEmpty && category == null) return const [];
    final starts = <BusinessTypeOption>[];
    final contains = <BusinessTypeOption>[];
    for (final c in cats) {
      for (final e in data[c] ?? const <(String, String)>[]) {
        final name = _name(e, lang);
        if (q.isEmpty) {
          starts.add((category: c, subtype: name));
          continue;
        }
        final hay = [norm(e.$1), norm(e.$2)];
        if (hay.any((h) => h.startsWith(q))) {
          starts.add((category: c, subtype: name));
        } else if (hay.any((h) => h.contains(q))) {
          contains.add((category: c, subtype: name));
        }
      }
    }
    return [...starts, ...contains];
  }

  /// «Фаолият тури» таклифлари: номи мос турлар (бўш сўров — 30 тасининг ҳаммаси), сўнг аниқроқ тури мос
  /// келган турлар шу аниқроқ тури билан (масалан «дорих» → «Савдо ва дўконлар · Дорихона»).
  /// [labelOf] — турнинг экрандаги номи (`context.tr(c.labelKey)`).
  static List<BusinessTypeOption> categoryOptions(String query, String lang, String Function(BusinessCategory) labelOf) {
    final q = norm(query);
    if (q.isEmpty) return [for (final c in BusinessCategory.values) (category: c, subtype: null)];
    final byName = <BusinessTypeOption>[
      for (final c in BusinessCategory.values)
        if (norm(labelOf(c)).contains(q)) (category: c, subtype: null),
    ];
    final named = {for (final o in byName) o.category};
    final bySubtype = subtypeOptions(query, lang).where((o) => !named.contains(o.category));
    return [...byName, ...bySubtype];
  }
}
